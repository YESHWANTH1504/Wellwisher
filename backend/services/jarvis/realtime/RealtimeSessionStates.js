/**
 * RealtimeSessionStates
 * Explicit state machine definitions for JARVIS Realtime Sessions.
 * No ambiguous boolean states.
 */

const REALTIME_SESSION_STATES = Object.freeze({
  IDLE: 'IDLE',
  CONNECTING: 'CONNECTING',
  CONNECTED: 'CONNECTED',
  LISTENING: 'LISTENING',
  USER_SPEAKING: 'USER_SPEAKING',
  PROCESSING: 'PROCESSING',
  ASSISTANT_SPEAKING: 'ASSISTANT_SPEAKING',
  INTERRUPTED: 'INTERRUPTED',
  RECONNECTING: 'RECONNECTING',
  ERROR: 'ERROR',
  DISCONNECTING: 'DISCONNECTING',
  DISCONNECTED: 'DISCONNECTED'
});

const VALID_TRANSITIONS = {
  [REALTIME_SESSION_STATES.IDLE]: [
    REALTIME_SESSION_STATES.CONNECTING,
    REALTIME_SESSION_STATES.DISCONNECTING,
    REALTIME_SESSION_STATES.DISCONNECTED
  ],
  [REALTIME_SESSION_STATES.CONNECTING]: [
    REALTIME_SESSION_STATES.CONNECTED,
    REALTIME_SESSION_STATES.ERROR,
    REALTIME_SESSION_STATES.DISCONNECTING,
    REALTIME_SESSION_STATES.DISCONNECTED
  ],
  [REALTIME_SESSION_STATES.CONNECTED]: [
    REALTIME_SESSION_STATES.LISTENING,
    REALTIME_SESSION_STATES.DISCONNECTING,
    REALTIME_SESSION_STATES.DISCONNECTED,
    REALTIME_SESSION_STATES.RECONNECTING,
    REALTIME_SESSION_STATES.ERROR
  ],
  [REALTIME_SESSION_STATES.LISTENING]: [
    REALTIME_SESSION_STATES.USER_SPEAKING,
    REALTIME_SESSION_STATES.PROCESSING,
    REALTIME_SESSION_STATES.DISCONNECTING,
    REALTIME_SESSION_STATES.DISCONNECTED,
    REALTIME_SESSION_STATES.ERROR
  ],
  [REALTIME_SESSION_STATES.USER_SPEAKING]: [
    REALTIME_SESSION_STATES.PROCESSING,
    REALTIME_SESSION_STATES.LISTENING,
    REALTIME_SESSION_STATES.DISCONNECTING,
    REALTIME_SESSION_STATES.DISCONNECTED,
    REALTIME_SESSION_STATES.ERROR
  ],
  [REALTIME_SESSION_STATES.PROCESSING]: [
    REALTIME_SESSION_STATES.ASSISTANT_SPEAKING,
    REALTIME_SESSION_STATES.LISTENING,
    REALTIME_SESSION_STATES.INTERRUPTED,
    REALTIME_SESSION_STATES.DISCONNECTING,
    REALTIME_SESSION_STATES.DISCONNECTED,
    REALTIME_SESSION_STATES.ERROR
  ],
  [REALTIME_SESSION_STATES.ASSISTANT_SPEAKING]: [
    REALTIME_SESSION_STATES.INTERRUPTED,
    REALTIME_SESSION_STATES.LISTENING,
    REALTIME_SESSION_STATES.CONNECTED,
    REALTIME_SESSION_STATES.DISCONNECTING,
    REALTIME_SESSION_STATES.DISCONNECTED,
    REALTIME_SESSION_STATES.ERROR
  ],
  [REALTIME_SESSION_STATES.INTERRUPTED]: [
    REALTIME_SESSION_STATES.LISTENING,
    REALTIME_SESSION_STATES.USER_SPEAKING,
    REALTIME_SESSION_STATES.PROCESSING,
    REALTIME_SESSION_STATES.DISCONNECTING,
    REALTIME_SESSION_STATES.DISCONNECTED
  ],
  [REALTIME_SESSION_STATES.RECONNECTING]: [
    REALTIME_SESSION_STATES.CONNECTED,
    REALTIME_SESSION_STATES.ERROR,
    REALTIME_SESSION_STATES.DISCONNECTED
  ],
  [REALTIME_SESSION_STATES.ERROR]: [
    REALTIME_SESSION_STATES.RECONNECTING,
    REALTIME_SESSION_STATES.DISCONNECTED,
    REALTIME_SESSION_STATES.IDLE
  ],
  [REALTIME_SESSION_STATES.DISCONNECTING]: [
    REALTIME_SESSION_STATES.DISCONNECTED
  ],
  [REALTIME_SESSION_STATES.DISCONNECTED]: [
    REALTIME_SESSION_STATES.IDLE,
    REALTIME_SESSION_STATES.CONNECTING
  ]
};

function canTransition(fromState, toState) {
  if (fromState === toState) return true;
  const allowed = VALID_TRANSITIONS[fromState];
  return Array.isArray(allowed) && allowed.includes(toState);
}

module.exports = {
  REALTIME_STATES: REALTIME_SESSION_STATES,
  REALTIME_SESSION_STATES,
  VALID_TRANSITIONS,
  canTransition
};
